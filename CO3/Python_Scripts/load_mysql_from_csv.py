#!/usr/bin/env python3
"""Optional MySQL 8.0 loader for the three ShopNest schemas.

Requires: pip install mysql-connector-python
Run schema DDL first, then supply the CSV generated by generate_order_line_csv.py.
This loader has not been run against a live MySQL server in the authoring environment.
"""
import argparse, csv, mysql.connector
from pathlib import Path
from collections import OrderedDict


def chunks(iterable, size):
    batch=[]
    for x in iterable:
        batch.append(x)
        if len(batch)>=size:
            yield batch; batch=[]
    if batch: yield batch


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--csv',required=True)
    ap.add_argument('--host',default='localhost'); ap.add_argument('--user',default='root')
    ap.add_argument('--password',default=''); ap.add_argument('--database',default='shopnest_co3')
    ap.add_argument('--batch-size',type=int,default=2000)
    args=ap.parse_args()
    csv_path=Path(args.csv)
    con=mysql.connector.connect(host=args.host,user=args.user,password=args.password,database=args.database)
    cur=con.cursor()
    # Pass 1: collect compact dimensions and addresses from the common CSV.
    customers={}; suppliers={}; categories={}; warehouses={}; products={}; pins={}; addresses={}
    with csv_path.open(newline='',encoding='utf-8') as f:
        for r in csv.DictReader(f):
            cid=int(r['CustomerID']); sid=int(r['SupplierID']); cat=int(r['CategoryID']); wid=int(r['WarehouseID']); pid=int(r['ProductID']); pin=r['ShipPIN']
            customers[cid]=(cid,r['CustomerName'],r['CustomerEmail'])
            suppliers[sid]=(sid,r['SupplierName'],r['SupplierPhone'])
            categories[cat]=(cat,r['CategoryName']); warehouses[wid]=(wid,r['WarehouseCity'])
            products[pid]=(pid,r['ProductName'],float(r['UnitPrice']),cat,sid)
            pins[pin]=(pin,r['ShipCity'],r['ShipState'])
            addresses[(r['ShipStreet'],r['ShipCity'],pin)]=(r['ShipStreet'],r['ShipCity'],pin)
    # Populate UNF baseline (the first schema remains a wide repeated-fact relation).
    ins_unf='INSERT INTO order_line_unf VALUES('+','.join(['%s']*22)+')'
    with csv_path.open(newline='',encoding='utf-8') as f:
        reader=csv.DictReader(f)
        fields=reader.fieldnames
        for batch in chunks((tuple(int(r[k]) if k in {'OrderID','CustomerID','ShipPIN','ProductID','CategoryID','SupplierID','Quantity','WarehouseID'} else float(r[k]) if k=='UnitPrice' else r[k] for k in fields) for r in reader),args.batch_size):
            cur.executemany(ins_unf,batch); con.commit()
    # Load shared dimensions for 3NF.
    for table, data in [('customer_3nf',customers.values()),('supplier_3nf',suppliers.values()),('category_3nf',categories.values()),('warehouse_3nf',warehouses.values()),('product_3nf',products.values()),('postal_state_3nf',((p,state) for p,city,state in pins.values()))]:
        vals=list(data)
        if not vals: continue
        placeholders=','.join(['%s']*len(vals[0]))
        cur.executemany(f'INSERT IGNORE INTO {table} VALUES({placeholders})',vals); con.commit()
    # 3NF addresses contain street, city, PIN and reference a PIN->state relation.
    cur.executemany('INSERT IGNORE INTO shipping_address_3nf(ShipStreet,ShipCity,ShipPIN) VALUES(%s,%s,%s)',addresses.values()); con.commit()
    cur.execute('SELECT AddressID,ShipStreet,ShipCity,ShipPIN FROM shipping_address_3nf')
    addr3={(st,city,pin):aid for aid,st,city,pin in cur.fetchall()}
    # 4NF dimensions and BCNF address decomposition.
    for table, data in [('customer_4nf',customers.values()),('supplier_4nf',suppliers.values()),('category_4nf',categories.values()),('warehouse_4nf',warehouses.values()),('product_4nf',products.values()),('postal_area_4nf',pins.values())]:
        vals=list(data)
        if not vals: continue
        placeholders=','.join(['%s']*len(vals[0]))
        cur.executemany(f'INSERT IGNORE INTO {table} VALUES({placeholders})',vals); con.commit()
    cur.executemany('INSERT IGNORE INTO shipping_address_4nf(ShipStreet,ShipPIN) VALUES(%s,%s)',((st,pin) for st,city,pin in addresses)); con.commit()
    # Product independent values / 3NF cross-product (the generated lists are constant by product).
    tag_rows=[]; colour_rows=[]; tag_colour_rows=[]
    for pid in products:
        tags=('eco','fragile','priority'); colours=('black','blue')
        tag_rows.extend((pid,t) for t in tags); colour_rows.extend((pid,c) for c in colours)
        tag_colour_rows.extend((pid,t,c) for t in tags for c in colours)
    cur.executemany('INSERT IGNORE INTO product_tag_colour_3nf VALUES(%s,%s,%s)',tag_colour_rows)
    cur.executemany('INSERT IGNORE INTO product_tag_4nf VALUES(%s,%s)',tag_rows)
    cur.executemany('INSERT IGNORE INTO product_colour_4nf VALUES(%s,%s)',colour_rows)
    # 5NF sample projections are loaded from the declared six-tuple teaching instance.
    triples=[(1,1,1),(1,3,3),(2,1,2),(2,2,3),(3,1,1),(3,3,3)]
    sc={(s,c) for s,c,w in triples}; cw={(c,w) for s,c,w in triples}; sw={(s,w) for s,c,w in triples}
    cur.executemany('INSERT IGNORE INTO supply_supplier_category_5nf VALUES(%s,%s)',list(sc))
    cur.executemany('INSERT IGNORE INTO supply_category_warehouse_5nf VALUES(%s,%s)',list(cw))
    cur.executemany('INSERT IGNORE INTO supply_supplier_warehouse_5nf VALUES(%s,%s)',list(sw))
    # Stream order headers and line details into both normalised designs.
    with csv_path.open(newline='',encoding='utf-8') as f:
        reader=csv.DictReader(f); seen_orders=set(); batch3=[]; batch4=[]
        for r in reader:
            order=int(r['OrderID']); cid=int(r['CustomerID']); pid=int(r['ProductID']); qty=int(r['Quantity']); wid=int(r['WarehouseID'])
            if order not in seen_orders:
                seen_orders.add(order); aid=addr3[(r['ShipStreet'],r['ShipCity'],r['ShipPIN'])]
                cur.execute('INSERT IGNORE INTO orders_3nf VALUES(%s,%s,%s,%s)',(order,r['OrderDate'],cid,aid))
                cur.execute('INSERT IGNORE INTO orders_4nf VALUES(%s,%s,%s,%s,%s)',(order,r['OrderDate'],cid,r['ShipStreet'],r['ShipPIN']))
            batch3.append((order,pid,qty,wid)); batch4.append((order,pid,qty,wid))
            if len(batch3)>=args.batch_size:
                cur.executemany('INSERT IGNORE INTO order_item_3nf VALUES(%s,%s,%s,%s)',batch3)
                cur.executemany('INSERT IGNORE INTO order_item_4nf(OrderID,ProductID,Quantity,WarehouseID) VALUES(%s,%s,%s,%s)',batch4)
                con.commit(); batch3=[]; batch4=[]
        if batch3:
            cur.executemany('INSERT IGNORE INTO order_item_3nf VALUES(%s,%s,%s,%s)',batch3)
            cur.executemany('INSERT IGNORE INTO order_item_4nf(OrderID,ProductID,Quantity,WarehouseID) VALUES(%s,%s,%s,%s)',batch4); con.commit()
    cur.close(); con.close()
    print(f'Loaded common CSV into UNF, 3NF and BCNF/4NF/5NF designs: {csv_path}')
    print('Note: order_item_4nf.UnitPricePaid is added separately by SQL/02_task12_price_history_mysql.sql.')

if __name__=='__main__': main()
